"""로봇이 말하는 고정 문구 모음 (LLM 이 만들지 않는 말).

한 곳에 모으는 이유는 두 가지다.

1. 자가 트리거 검사를 빠짐없이 돌리기 위해서다. 이 문구에 긴급어가 섞이면 상시
   긴급어 감시가 스피커로 나간 로봇 자기 목소리를 다시 긴급어로 인식한다.
   tests/test_spoken_text.py 가 이 모듈의 모든 문구를 자동으로 훑는다.
2. 시각장애인 사용자 대상 문구는 감수 대상이라, 흩어져 있으면 검토가 어렵다.

Mission Manager 의 안내 멘트(MSG_*)는 vica_ros2_ws 쪽에 있다. 그쪽은 주행 상태를
아는 노드가 말해야 하기 때문이며, 같은 성격의 검사를 별도로 두고 있다.
"""
from __future__ import annotations

# 긴급어 감지 시의 응답. 실제 정지는 E-stop 래치 체인이 수행한다.
EMERGENCY_REPLY = "안전을 위해 멈추겠습니다."

# 발화를 접수했다는 즉시 신호.
#
# LLM 응답은 네트워크 왕복이 있어 수 초가 걸린다. 그동안 아무 소리도 나지 않으면
# 눈으로 확인할 수 없는 사용자는 로봇이 들었는지 알 수 없어 같은 말을 반복하게
# 되고, 그러면 대기열이 밀린다. 짧게 한 번 답하는 편이 낫다.
ACK_LISTENING = "네."

# STT 가 아무 말도 알아듣지 못했을 때. 침묵으로 두면 다시 말할 시점을 못 잡는다.
RETRY_PROMPT = "잘 듣지 못했습니다. 다시 말씀해 주세요."

# LLM 호출이 실패했을 때 (네트워크 등). 긴급어는 LLM 이전 단계에서 처리되므로
# 이 실패의 영향을 받지 않는다.
LLM_UNAVAILABLE = "죄송합니다. 지금은 요청을 처리할 수 없어요. 잠시 후 다시 말씀해 주세요."

# LLM 이 목록에 없는 목적지를 골랐을 때의 되묻기.
ASK_DESTINATION = "어디로 안내해드릴까요?"


def all_phrases() -> dict[str, str]:
    """이 모듈이 가진 고정 문구 전체 (검사·감수용)."""
    return {
        name: value
        for name, value in globals().items()
        if name.isupper() and isinstance(value, str)
    }
